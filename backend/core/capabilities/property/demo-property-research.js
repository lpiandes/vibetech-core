import { PropertyResearchCapability } from "./PropertyResearchCapability.js";
import { PropertyInterestCoordinator } from "../../employees/property-interest-coordinator/PropertyInterestCoordinator.js";

function printSection(title, value) {
  console.log(`\n=== ${title} ===`);
  console.log(JSON.stringify(value, null, 2));
}

async function main() {
  const capability = new PropertyResearchCapability();

  const property = {
    propertyId: "prop_demo_1",
    address: "68 Mystic Meadow Lane",
    city: "Hartford",
    state: "CT",
    price: 615000,
    description:
      "Light-filled home with room to grow, designed for calm, flexible everyday living.",
    highlights: [
      "Updated kitchen and open-plan living",
      "Natural light throughout",
      "Walkable to local amenities",
    ],
    considerations: [
      "Potential HOA items require clarification",
      "Check zoning-related constraints for planned renovations",
    ],
  };

  const buyerInquiry = {
    name: "Rachael Nguyen",
    email: "rachael.nguyen@example.com",
    phone: "(555) 019-2219",
    message:
      "Hi! I’m interested in this property and would like to discuss next steps today. Can you share a good walkthrough window? Anything urgent I should know about?",
    submittedAt: new Date().toISOString(),
    priority: "High",
  };

  const companyKnowledge = {
    responsePreferences: ["Use calm, confident language."],
    propertyShowingRules: [
      "Confirm preferred walkthrough windows before proposing times.",
      "Include a brief checklist of what the buyer should prepare.",
    ],
  };

  const output = capability.run({ property, buyerInquiry, companyKnowledge });

  printSection("propertySummary", output.propertySummary);
  printSection("buyerFit", output.buyerFit);
  printSection("sellingPoints", output.sellingPoints);
  printSection("buyerConsiderations", output.buyerConsiderations);
  printSection(
    "recommendedTalkingPoints",
    output.recommendedTalkingPoints,
  );
  printSection("confidence", output.confidence);
  printSection("reasoning", output.reasoning);

  const coordinator = new PropertyInterestCoordinator();
  const { reviewWork, employeeSummary } = await coordinator.run({
    inquiry: buyerInquiry,
    property,
    companyContext: {
      responsePolicy:
        "Respond with clear next steps, confirm key property details, and keep all communications governance-ready until guidance is provided.",
    },
  });

  printSection("employeeSummary (from PropertyInterestCoordinator)", employeeSummary);
  printSection(
    "reviewWork.attorneyNote (enriched with capability output)",
    reviewWork.attorneyNote,
  );
  printSection(
    "reviewWork.employeeThinking (generated by existing view adapter)",
    reviewWork.employeeThinking,
  );
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});

